/**
 * Packs the Godot addon (addon/godot_pilot) into a TypeScript file, so the compiled
 * server carries the addon inside itself and can install it into any project.
 *
 * Run automatically by `bun run build` and before every test run (see bunfig.toml).
 * The output file is generated; never edit it by hand.
 */
import { join, relative } from "node:path";

const repositoryRoot = join(import.meta.dir, "..");
const addonSourceDirectory = join(repositoryRoot, "addon", "godot_pilot");
const outputFilePath = join(repositoryRoot, "server", "src", "addon", "addon-files.generated.ts");

/** Files Godot creates by itself; they must not be shipped. */
const IGNORED_FILE_PATTERN = /\.(uid|import)$/;

const addonFiles: Record<string, string> = {};
for (const absolutePath of new Bun.Glob("**/*").scanSync({ cwd: addonSourceDirectory, absolute: true })) {
  const relativePath = relative(addonSourceDirectory, absolutePath).replaceAll("\\", "/");
  if (IGNORED_FILE_PATTERN.test(relativePath)) {
    continue;
  }
  addonFiles[relativePath] = (await Bun.file(absolutePath).text()).replaceAll("\r\n", "\n");
}

const sortedEntries = Object.entries(addonFiles).sort(([firstPath], [secondPath]) =>
  firstPath.localeCompare(secondPath),
);
const fileContent = [
  "// Generated by scripts/bundle-addon.ts from addon/godot_pilot. Do not edit by hand.",
  "",
  "/** Addon files by their path inside the addon folder. */",
  "export const bundledAddonFiles: Readonly<Record<string, string>> = {",
  ...sortedEntries.map(([path, content]) => `  ${JSON.stringify(path)}: ${JSON.stringify(content)},`),
  "};",
  "",
].join("\n");

// Rewriting an unchanged file would only wake up file watchers for nothing.
const outputFile = Bun.file(outputFilePath);
if (!(await outputFile.exists()) || (await outputFile.text()) !== fileContent) {
  await Bun.write(outputFilePath, fileContent);
  console.log(`Bundled ${sortedEntries.length} addon files into ${relative(repositoryRoot, outputFilePath)}`);
}
